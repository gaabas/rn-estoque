import { expect, test } from '@playwright/test'

test('registra, complementa e conclui uma compra preservando a contagem', async ({ page }) => {
  await page.goto('/')
  await page.getByRole('searchbox').fill('creme de leite')
  await page.getByRole('button', { name: /Creme de leite/ }).click()
  await page.getByRole('button', { name: 'Registrar quantidade' }).click()
  await expect(page.getByText('caixas', { exact: true })).toBeVisible()
  await page.getByLabel('Quantidade conferida').fill('8')
  await page.getByRole('button', { name: 'Salvar contagem' }).click()
  await expect(page.getByText('Contagem salva neste aparelho.')).toBeVisible()
  await page.getByRole('button', { name: 'Pedir compra' }).click()
  await expect(page.getByRole('button', { name: 'Pedir compra' })).toHaveCount(0)
  await page.getByRole('button', { name: 'Compra pendente', exact: true }).click()
  await page.getByLabel('Motivo').fill('Estrogonofe amanhã')
  await page.getByLabel('Quantidade sugerida').fill('12')
  await page.getByRole('button', { name: 'Salvar detalhes' }).click()
  await page.getByRole('button', { name: 'Fechar painel' }).click()
  await page.getByRole('button', { name: /^Compras/ }).click()
  await expect(page.getByRole('button', { name: 'Marcar como comprado' })).toHaveCount(1)
  await expect(page.getByText('8 caixas', { exact: true })).toBeVisible()
  await expect(page.getByText('Estrogonofe amanhã')).toBeVisible()
  await expect(page.getByText(/12 caixas/)).toBeVisible()
  await page.getByRole('button', { name: 'Marcar como comprado' }).click()
  await expect(page.getByText('Nenhuma compra pendente.')).toBeVisible()
  await page.getByRole('button', { name: 'Estoque', exact: true }).click()
  await page.getByRole('button', { name: /Creme de leite/ }).click()
  await page.getByRole('button', { name: 'Ver histórico' }).click()
  const history = page.getByRole('region', { name: 'Histórico' })
  for (const label of ['Pedido concluído', 'Pedido aberto']) {
    await expect(history.getByText(label, { exact: true })).toBeVisible()
  }
  await expect(history.getByText('Contagem física', { exact: true })).toHaveCount(2)
  await expect(history.getByText('8 caixas', { exact: true })).toBeVisible()
})

test('distingue zero, correção, nova observação e desfazer', async ({ page }) => {
  await page.goto('/')
  const item = page.getByRole('button', { name: /Farinha de trigo/ })
  await expect(item).toContainText('Sem contagem')
  await item.click()
  await page.getByRole('button', { name: 'Registrar quantidade' }).click()
  await page.getByLabel('Quantidade conferida').fill('0')
  await page.getByRole('button', { name: 'Salvar contagem' }).click()
  await page.getByRole('button', { name: 'Fechar painel' }).click()
  await page.reload()
  await expect(item).toContainText('0 kg')
  await item.click()
  await page.getByRole('button', { name: 'Corrigir última contagem' }).click()
  await page.getByLabel('Quantidade conferida').fill('1,5')
  await page.getByRole('button', { name: 'Salvar correção' }).click()
  await page.getByRole('button', { name: 'Registrar quantidade' }).click()
  await page.getByLabel('Quantidade conferida').fill('3')
  await page.getByRole('button', { name: 'Salvar contagem' }).click()
  await page.getByRole('button', { name: 'Desfazer', exact: true }).click()
  await page.getByRole('button', { name: 'Ver histórico' }).click()
  await expect(page.getByText('0 kg → 1,5 kg')).toBeVisible()
  await expect(page.getByText('Equipe (demonstração)').first()).toBeVisible()
  await expect(page.getByText('Contagem desfeita', { exact: true })).toBeVisible()
  await page.getByRole('button', { name: 'Fechar painel' }).click()
  await expect(item).toContainText('1,5 kg')
})

test('reabre a interface em modo offline com os registros locais', async ({ page, context }) => {
  await page.goto('/')
  await page.getByRole('button', { name: /Creme de leite/ }).click()
  await page.getByRole('button', { name: 'Pedir compra' }).click()
  const manifest = await page.request.get('/manifest.webmanifest')
  expect((await manifest.json()).display).toBe('standalone')
  await page.waitForFunction(() => Boolean(navigator.serviceWorker.controller))
  await page.close()
  await context.setOffline(true)
  const offlinePage = await context.newPage()
  await offlinePage.goto('/')
  await expect(offlinePage.getByText(/Sem conexão/)).toBeVisible()
  const item = offlinePage.getByRole('button', { name: /Creme de leite/ })
  await expect(item).toContainText('Compra pendente')
  await item.click()
  await offlinePage.getByRole('button', { name: 'Registrar quantidade' }).click()
  await offlinePage.getByLabel('Quantidade conferida').fill('7')
  await offlinePage.getByRole('button', { name: 'Salvar contagem' }).click()
  await expect(offlinePage.getByText('Contagem salva neste aparelho.')).toBeVisible()
  await offlinePage.reload()
  await expect(item).toContainText('7 caixas')
})

test('avisa quando o armazenamento local está ilegível', async ({ page }) => {
  await page.addInitScript(() => localStorage.setItem('rn-estoque-demo-v1', 'null'))
  await page.goto('/')
  await expect(page.getByRole('alert')).toContainText('Não foi possível ler os registros')
  await expect(page.getByRole('searchbox')).toBeVisible()
})
